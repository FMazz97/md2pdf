// Prints the HTML to PDF with Chrome/Edge: "page / total" footer and page numbers in the table of contents.
// Usage: node print-pdf.mjs <html-url> <output.pdf> <browser-path>
//
// Two passes: the first prints a draft PDF with invisible markers inside the headings, reads the page text
// with pdf.js and finds the page of each heading; the second writes the numbers into the table of contents
// (fixed width, so the pagination does not change) and prints the final PDF.
import { readFile } from 'node:fs/promises';
import puppeteer from 'puppeteer-core';
import * as pdfjs from 'pdfjs-dist/legacy/build/pdf.mjs';

const [, , url, out, exe] = process.argv;
if (!url || !out || !exe) {
  console.error('Usage: node print-pdf.mjs <html-url> <output.pdf> <browser-path>');
  process.exit(1);
}

const footer = `<div style="width:100%;font-size:9px;color:#59636e;text-align:center;
  font-family:Arial,Helvetica,sans-serif;"><span class="pageNumber"></span> / <span class="totalPages"></span></div>`;

const pdfOptions = {
  format: 'A4',
  printBackground: true,
  displayHeaderFooter: true,
  headerTemplate: '<div></div>',
  footerTemplate: footer,
  margin: { top: '18mm', bottom: '18mm', left: '16mm', right: '16mm' }, // same as @page in the CSS
};

// Fills the leader dots of each entry with a whole number of dots, evenly distributed:
// the first starts right after the title and the last ends right before the page number, with no clipping.
const fillDots = (page) => page.evaluate(() => {
  document.querySelectorAll('.toc .dots').forEach((d) => {
    d.textContent = '';
    const fs = parseFloat(getComputedStyle(d).fontSize);
    const n = Math.max(1, Math.floor(d.clientWidth / (fs * 0.75)));
    d.innerHTML = '<i>.</i>'.repeat(n);
  });
});

// Page (1-based) of the first @@H<n>@@ marker found in the PDF text
async function pagesOfMarkers(buf, count) {
  const doc = await pdfjs.getDocument({
    data: new Uint8Array(buf), useSystemFonts: true, isEvalSupported: false, verbosity: 0,
  }).promise;
  const pages = new Array(count).fill('');
  for (let p = 1; p <= doc.numPages; p++) {
    const tc = await (await doc.getPage(p)).getTextContent();
    const text = tc.items.map((i) => i.str).join('');
    for (const m of text.matchAll(/@@H(\d+)@@/g)) {
      const n = Number(m[1]);
      if (n < count && pages[n] === '') pages[n] = p;
    }
  }
  return pages;
}

const browser = await puppeteer.launch({ executablePath: exe, headless: true });
try {
  const page = await browser.newPage();
  await page.goto(url, { waitUntil: 'load' });

  // Code colors as on GitHub (reclassifies the tokens generated by Pandoc)
  await page.addScriptTag({ content: await readFile(new URL('./code-colors.js', import.meta.url), 'utf8') });
  await page.evaluate(() => window.githubCodeColors(document));

  // Measurements as in the printed page: A4 usable width (210 mm - 2 x 16 mm = 178 mm)
  await page.setViewport({ width: Math.round((178 / 25.4) * 96), height: 1000 });
  await page.emulateMediaType('print');

  // Lists, code, tables, quotes and alerts taller than 40% of the usable area (261 mm) may split across pages;
  // smaller ones stay whole. The 0.4 factor sets how strict the rule is: higher values keep larger blocks whole.
  await page.evaluate(() => {
    const limit = 0.4 * (261 / 25.4) * 96;
    document.querySelectorAll(
      'section.doc :is(ul, ol, li, pre, table, blockquote, figure, div.note, div.tip, div.important, div.warning, div.caution)'
    ).forEach((el) => {
      if (el.getBoundingClientRect().height > limit) el.classList.add('breakable');
    });
  });

  // Pass 1: invisible markers at the start of each heading that appears in the table of contents
  const ids = await page.evaluate(() => {
    const hs = [...document.querySelectorAll('section.doc h1, section.doc h2, section.doc h3')].filter((h) => h.id);
    hs.forEach((h, i) => {
      const s = document.createElement('span');
      s.className = 'hm';
      s.textContent = `@@H${i}@@`;
      h.prepend(s);
    });
    return hs.map((h) => h.id);
  });
  await fillDots(page);
  const draft = await page.pdf(pdfOptions);
  const pages = await pagesOfMarkers(draft, ids.length);
  const missing = pages.filter((x) => x === '').length;
  if (missing) console.warn(`Warning: page not found for ${missing} table-of-contents headings.`);

  // Pass 2: page numbers into the table of contents, markers removed, final PDF
  await page.evaluate((ids, pages) => {
    document.querySelectorAll('.hm').forEach((e) => e.remove());
    ids.forEach((id, i) => {
      const el = [...document.querySelectorAll('.toc .pn')].find((e) => e.dataset.id === id);
      if (el) el.textContent = pages[i];
    });
  }, ids, pages);
  await fillDots(page); // the width of the numbers changed: recompute the dots
  await page.pdf({ ...pdfOptions, path: out });
} finally {
  await browser.close();
}
